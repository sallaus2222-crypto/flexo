def configure(database_url="", use_sqlite=False):
    global DATABASE_URL, USE_SQLITE
    DATABASE_URL = database_url or os.getenv("DATABASE_URL", "")
    USE_SQLITE = use_sqlite
    if not DATABASE_URL and not USE_SQLITE:
        raise RuntimeError("Configure DATABASE_URL or explicitly enable USE_SQLITE for local development.")


@contextmanager
def _connection():
    if DATABASE_URL:
        import psycopg
        conn = psycopg.connect(DATABASE_URL, connect_timeout=10, sslmode="require")
        conn.prepare_threshold = None
    elif USE_SQLITE:
        conn = sqlite3.connect(SQLITE_PATH, timeout=10)
    else:
        raise RuntimeError("Database is not configured.")

    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _sql(statement):
    return statement.replace("?", "%s") if DATABASE_URL else statement


def _fetch_dataframe(statement, params=()):
    with _connection() as conn:
        cursor = conn.cursor()
        try:
            cursor.execute(_sql(statement), params)
            rows = cursor.fetchall()
            columns = [
                column.name if hasattr(column, "name") else column[0]
                for column in cursor.description
            ]
            return pd.DataFrame.from_records(rows, columns=columns)
        finally:
            cursor.close()


