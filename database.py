def registrar_retrabalho(op, motivo, descricao):
    with _connection() as conn:
        cursor = conn.cursor()
        try:
            cursor.execute(_sql('''
        UPDATE montagens
        SET houve_retrabalho = 'Sim', motivo_retrabalho = ?, descricao_retrabalho = ?
        WHERE op = ?
            '''), (motivo, descricao, op))
        finally:
            cursor.close()


def carregar_dados():
    return _fetch_dataframe("SELECT * FROM montagens")


def buscar_historico_op(op):
    query = "SELECT * FROM montagens WHERE op = ? ORDER BY data_registro DESC LIMIT 1"
    return _fetch_dataframe(query, (op,))


def buscar_montagens_op(op):
    query = "SELECT * FROM montagens WHERE op LIKE ? ORDER BY data_registro DESC"
    return _fetch_dataframe(query, (f"%{op}%",))


def registrar_observacao_melhoria(op, observacao):
    with _connection() as conn:
        cursor = conn.cursor()
        try:
            cursor.execute(
                _sql('INSERT INTO observacoes_melhoria (op, observacao, data_registro) VALUES (?, ?, ?)'),
                (op, observacao, datetime.now().isoformat(timespec="seconds"))
            )
        finally:
            cursor.close()


def buscar_observacoes_melhoria(op):
    return _fetch_dataframe(
        'SELECT observacao, data_registro FROM observacoes_melhoria WHERE op = ? ORDER BY id DESC',
        (op,)
    )


